import * as THREE from 'three';
import { InkRenderer } from '/src/engine/render/renderer.ts';
import { makeInkMaterial } from '/src/engine/render/ink-material.ts';
import { GeometryBuilder, ALWAYS_COLOR } from '/src/engine/render/geometry-builder.ts';
import { WalkArms } from '/src/systems/player/walk-arms.ts';
import { defaultLook, CHARACTERS } from '/src/content/characters.ts';
import { color } from '/src/content/palette.ts';
const canvas = document.querySelector('canvas');
const renderer = new InkRenderer(canvas);
renderer.camera.position.set(0,1.6,0);
renderer.camera.fov=78;renderer.camera.updateProjectionMatrix();
const g=new GeometryBuilder();
g.box({x:-6,y:0,z:-2.65},{x:6,y:5,z:-2.35},{pz:color('limewash')},{pz:ALWAYS_COLOR});
g.box({x:-6,y:-.2,z:-6},{x:6,y:0,z:6},{py:color('sand')},{py:ALWAYS_COLOR});
const material=makeInkMaterial();
renderer.scene.add(new THREE.Mesh(g.build(),material));
renderer.scene.add(renderer.camera);
const arms=new WalkArms(renderer.camera,renderer.brushSpray);
const held={item:'brush',aiming:false,painting:true,paintColor:color('limewash'),paintTarget:new THREE.Vector3(0,1.6,-2.35)};
const player={speed:0,grounded:true,flying:false,gliding:false,waterMode:'dry'};
window.qa={renderer,arms,held,player,ready:false,frames:0,errors:[],positions:[]};
const oldError=console.error;console.error=(...a)=>{window.qa.errors.push(a.map(String).join(' '));oldError(...a)};
for(const [id,key] of [['cream','limewash'],['red','red'],['blue','blue']])document.getElementById(id).onclick=()=>{held.paintColor=color(key);held.painting=true;document.getElementById('status').textContent=id};
document.getElementById('stop').onclick=()=>held.painting=false;
document.getElementById('character').innerHTML=CHARACTERS.filter(c=>['courier','mason','platformer/Character'].includes(c.key)).map(c=>`<option value="${c.key}">${c.name}</option>`).join('');
document.getElementById('character').onchange=e=>arms.setLook(defaultLook(e.target.value));
await renderer.texturesReady;
let last=performance.now();
function frame(now){const dt=Math.min(.05,(now-last)/1000);last=now;arms.update(dt,player,held,true);renderer.render();window.qa.frames++;if(window.qa.frames>10)window.qa.ready=true;requestAnimationFrame(frame)}
requestAnimationFrame(frame);document.getElementById('status').textContent='修复模式：笔尖和喷雾跟随墙面颜色';
window.addEventListener('resize',()=>renderer.resize());
