import { Vector3 } from 'three';
import { InfectionSystem } from '../../src/systems/combat/infection';
import { npcBattles } from '../../src/systems/combat/npc-combat';
import { shared } from '../../src/engine/render/ink-material';
import { headless } from '../../tests/support/headless';

const h = headless();
h.physics.ground = () => 0;
h.place(0, 0, 0);
const site = { scene: { kind: 'wild' as const }, x: 5, y: 0, z: 0 };
h.ctx.state.infectedPeople.set('resident:diagnostic', site);
h.ctx.state.inkAreas.set('wild:5:0', site);
const sys = new InfectionSystem(h.ctx);
const enemies = () => [...npcBattles(h.ctx).enemies].filter(e => e.alive());
const snapshot = () => ({ clock: h.ctx.state.clock, alive: enemies().length, infectedPeople: h.ctx.state.infectedPeople.size, inkAreas: h.ctx.state.inkAreas.size, shaderAreas: shared.uInkAreaCount.value });
h.run(0.5, dt => sys.update(dt));
const before = snapshot();
enemies()[0]!.damage(10000, new Vector3());
h.run(1, dt => sys.update(dt));
const afterKill = snapshot();
h.place(120, 0, 0);
h.run(0.6, dt => sys.update(dt));
h.place(0, 0, 0);
h.run(0.6, dt => sys.update(dt));
const afterReturn = snapshot();
const returned = enemies()[0];
h.ctx.state.calendarOffset = 900;
h.run(0.6, dt => sys.update(dt));
const afterNight = { ...snapshot(), sameMonster: returned === enemies()[0] };
h.ctx.state.calendarOffset = 0;
h.run(0.6, dt => sys.update(dt));
const afterDay = { ...snapshot(), sameMonster: returned === enemies()[0] };
const wild = h.ctx.scenes.active;
h.ctx.scenes.active = { ...wild, ref: { kind: 'city', id: 'c0_0' } };
h.run(0.6, dt => sys.update(dt));
const acrossTownBorder = snapshot();
h.ctx.scenes.active = wild;
h.run(0.6, dt => sys.update(dt));
const backAcrossBorder = snapshot();
console.log(JSON.stringify({ before, afterKill, afterReturn, afterNight, afterDay, acrossTownBorder, backAcrossBorder }, null, 2));
sys.dispose();
